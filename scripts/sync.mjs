#!/usr/bin/env node
/**
 * sync.mjs — measured phrase timing. Writes <project>/js/sync.js: for every cue, the time (s, from the cue start) at
 * which each character of the on-screen text is spoken, measured from that cue's own take (audio/cues/<id>.wav).
 *
 *   node sync.mjs <projectDir>            (after tts.mjs; re-run whenever a cue's audio changes)
 *
 * Only recorded takes are measured: placeholder cues (placeholder: true in js/cues.js — silent, estimated timing) are
 * skipped and keep the estimate until they are recorded; "narration": false has nothing to measure.
 *
 * cue(id).when('phrase') in scenes.js then returns the measured moment instead of the character estimate, so a number
 * lands exactly on the word that says it. When a take and js/sync.js disagree (narration re-generated, sync not
 * re-run) the player falls back to the estimate and warns once; check.mjs warns too.
 *
 * How: the take's loudness envelope gives the voiced stretches and the pauses between them. The spoken text (`say`,
 * directions in [..] removed) is laid over the voiced time at an even syllable rate, then every comma/full stop is
 * snapped to the pause nearest to where it falls, so each clause starts where the voice really starts it. The screen
 * text (`text`: "1,000억", "AI") and the spoken text ("천억", "에이아이") are paired word by word (common words anchor,
 * the rest is shared out in between), so any phrase of the screen text maps to the moment its first syllable starts.
 * Local signal analysis only — the audio is never transcribed or sent anywhere.
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const ROOT = path.resolve(process.argv[2] || '.');
if (!fs.existsSync(path.join(ROOT, 'js/cues.js'))) { console.error(`✖ no js/cues.js in ${ROOT} — run tts.mjs first`); process.exit(2); }
const box = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(ROOT, 'js/cues.js'), 'utf8'), box);
const DATA = box.window.VIDEO_DATA;
if (DATA.narration === false) {
  console.log('no narration (narration: false) — nothing to measure; cue().when() uses the estimate');
  fs.writeFileSync(path.join(ROOT, 'js/sync.js'), '// Generated by sync.mjs — no narration (narration: false).\nwindow.SYNC = {};\n');
  process.exit(0);
}
const cues = DATA.cues;

const PUNCT = /[\s.,!?·…"'“”‘’()\[\]-]/;
const isUnit = (ch) => !PUNCT.test(ch);
const units = (s) => [...s].filter(isUnit).length;
const strip = (s) => s.replace(/\[[^\]]*\]/g, '').replace(/<\|[^|]*\|>/g, '').replace(/<\/?[a-z]+>/gi, '').replace(/\s+/g, ' ').trim();   // directions, <|…|> tokens, <emphasis>…</emphasis>

function readWav(file) {
  const b = fs.readFileSync(file);
  let p = 12, fmt = null, data = null;
  while (p + 8 <= b.length) {
    const id = b.toString('ascii', p, p + 4), sz = b.readUInt32LE(p + 4);
    if (id === 'fmt ') fmt = { ch: b.readUInt16LE(p + 10), sr: b.readUInt32LE(p + 12), bits: b.readUInt16LE(p + 22) };
    if (id === 'data') { data = b.subarray(p + 8, p + 8 + sz); break; }
    p += 8 + sz + (sz & 1);
  }
  if (!fmt || !data || fmt.bits !== 16) throw new Error('unsupported wav ' + file);
  const n = Math.floor(data.length / 2 / fmt.ch), x = new Float32Array(n);
  for (let i = 0; i < n; i++) { let v = 0; for (let c = 0; c < fmt.ch; c++) v += data.readInt16LE((i * fmt.ch + c) * 2); x[i] = v / fmt.ch / 32768; }
  return { sr: fmt.sr, x, dur: n / fmt.sr };
}

// voiced stretches: 10 ms RMS frames above (peak − 38 dB); dips shorter than 90 ms are not pauses
function voiced({ sr, x }) {
  const hop = Math.round(sr * 0.01), F = Math.floor(x.length / hop), db = new Float32Array(F);
  let peak = -120;
  for (let f = 0; f < F; f++) {
    let s = 0;
    for (let i = f * hop; i < (f + 1) * hop; i++) s += x[i] * x[i];
    db[f] = 10 * Math.log10(s / hop + 1e-12);
    if (db[f] > peak) peak = db[f];
  }
  if (peak < -70) return [];   // digital silence: a placeholder take
  const th = peak - 38, on = [...db].map((v) => v > th);
  const regs = [];
  for (let f = 0; f < F; f++) {
    if (!on[f]) continue;
    let g = f; while (g < F && on[g]) g++;
    regs.push([f * 0.01, g * 0.01]); f = g;
  }
  const out = [];
  for (const r of regs) {
    const last = out[out.length - 1];
    if (last && r[0] - last[1] < 0.09) last[1] = r[1];
    else if (r[1] - r[0] >= 0.03 || !last) out.push(r.slice());
  }
  return out;
}

// unit index (0..N) of the spoken text → seconds, from the voiced stretches and the punctuation of `say`
function timeline(say, regs) {
  const chars = [...say], N = units(say);
  const T0 = regs[0][0], T1 = regs[regs.length - 1][1];
  const gaps = regs.slice(1).map((r, i) => [regs[i][1], r[0]]);
  // voiced-time helpers inside [a, b]
  const vIn = (a, b) => regs.reduce((s, r) => s + Math.max(0, Math.min(b, r[1]) - Math.max(a, r[0])), 0);
  const atV = (a, b, v) => { // the time in [a, b] after v seconds of voice
    let left = v;
    for (const r of regs) {
      const s = Math.max(a, r[0]), e = Math.min(b, r[1]);
      if (e <= s) continue;
      if (left <= e - s) return s + left;
      left -= e - s;
    }
    return b;
  };
  // punctuation boundaries (unit index after which a comma/stop/question comes)
  const bounds = [];
  let u = 0;
  chars.forEach((ch) => { if (isUnit(ch)) u++; else if (/[,.!?…]/.test(ch) && u > 0 && u < N) bounds.push(u); });
  const ub = [...new Set(bounds)];
  // predicted time of each boundary at an even rate over all voice, then a monotonic match to the pauses (DP)
  const VT = vIn(T0, T1);
  const pred = ub.map((k) => atV(T0, T1, (VT * k) / N));
  const MAXD = 0.6, MISS = MAXD;
  const P = ub.length, G = gaps.length;
  const cost = Array.from({ length: P + 1 }, () => new Float64Array(G + 1).fill(Infinity));
  const back = Array.from({ length: P + 1 }, () => new Int32Array(G + 1));
  cost[0].fill(0);
  for (let i = 1; i <= P; i++) for (let j = 0; j <= G; j++) {
    let best = cost[i - 1][j] + MISS, b = -1;                       // boundary i has no pause
    if (j > 0 && cost[i][j - 1] < best) { best = cost[i][j - 1]; b = -2; } // pause j is spare (TTS breath)
    if (j > 0) {
      const g = gaps[j - 1], d = Math.abs(pred[i - 1] - (g[0] + g[1]) / 2);
      if (d < MAXD && cost[i - 1][j - 1] + d < best) { best = cost[i - 1][j - 1] + d; b = j - 1; }
    }
    cost[i][j] = best; back[i][j] = b;
  }
  for (let j = 1; j <= G; j++) if (cost[0][j] > cost[0][j - 1]) cost[0][j] = cost[0][j - 1];
  const knots = [[0, T0]];
  const snap = [];
  for (let i = P, j = G; i > 0;) {
    const b = back[i][j];
    if (b === -2) { j--; continue; }
    if (b >= 0) snap.push([ub[i - 1], gaps[b]]);
    if (b >= 0) j--;
    i--;
  }
  snap.reverse().forEach(([k, g]) => { knots.push([k, g[0]]); knots.push([k, g[1]]); });
  knots.push([N, T1]);
  if (process.env.SYNC_DEBUG && say.includes(process.env.SYNC_DEBUG))
    console.log({ regs: regs.map((r) => r.map((v) => +v.toFixed(2))), ub, pred: pred.map((v) => +v.toFixed(2)), knots });
  return (k) => {
    k = Math.max(0, Math.min(N, k));
    // the last knot at or before k, the first after it (equal unit indices = a pause: take its far side)
    let a = knots[0], b = knots[knots.length - 1];
    for (const kn of knots) { if (kn[0] <= k) a = kn; }
    for (const kn of knots) { if (kn[0] > k) { b = kn; break; } }
    if (a[0] === b[0]) return a[1];
    const f = (k - a[0]) / (b[0] - a[0]);
    return atV(a[1], b[1], vIn(a[1], b[1]) * f);
  };
}

// screen text char index → spoken unit index: words paired by an LCS on their normalised form; unpaired runs are
// shared out in proportion to their units
function textToSay(text, say) {
  const words = (s) => {
    const out = [];
    let u = 0;
    const re = /\S+/g;
    let m;
    while ((m = re.exec(s))) {
      const w = m[0], n = units(w);
      out.push({ w, key: [...w].filter(isUnit).join(''), i0: m.index, u0: u, n });
      u += n;
    }
    return out;
  };
  const A = words(text), B = words(say);
  const L = Array.from({ length: A.length + 1 }, () => new Int32Array(B.length + 1));
  for (let i = A.length - 1; i >= 0; i--) for (let j = B.length - 1; j >= 0; j--)
    L[i][j] = A[i].key && A[i].key === B[j].key ? L[i + 1][j + 1] + 1 : Math.max(L[i + 1][j], L[i][j + 1]);
  const pairs = [];
  for (let i = 0, j = 0; i < A.length && j < B.length;) {
    if (A[i].key && A[i].key === B[j].key) { pairs.push([i, j]); i++; j++; }
    else if (L[i + 1][j] >= L[i][j + 1]) i++; else j++;
  }
  const NA = units(text), NB = units(say);
  // anchors in unit space: (text unit, say unit) at the start and end of every paired word
  const anc = [[0, 0]];
  for (const [i, j] of pairs) { anc.push([A[i].u0, B[j].u0]); anc.push([A[i].u0 + A[i].n, B[j].u0 + B[j].n]); }
  anc.push([NA, NB]);
  const mapU = (ua) => {
    let a = anc[0], b = anc[anc.length - 1];
    for (const p of anc) if (p[0] <= ua) a = p;
    for (const p of anc) if (p[0] > ua) { b = p; break; }
    if (b[0] === a[0]) return a[1];
    return a[1] + ((ua - a[0]) / (b[0] - a[0])) * (b[1] - a[1]);
  };
  // per character of the screen text: units before it
  const at = [];
  let u = 0;
  for (const ch of [...text]) { at.push(mapU(u)); if (isUnit(ch)) u++; }
  return at;
}

const SYNC = {};
let n = 0, warn = 0;
const skipped = [];   // placeholder cues: not recorded yet, when() keeps the estimate
for (const c of cues) {
  if (c.placeholder) { skipped.push(c.id); continue; }
  const f = path.join(ROOT, 'audio/cues', c.id + '.wav');
  if (!fs.existsSync(f)) { console.warn('no take for', c.id); warn++; continue; }
  const wav = readWav(f);
  if (Math.abs(wav.dur - c.duration) > 0.01) { console.warn(`${c.id}: take ${wav.dur.toFixed(3)} s ≠ cue ${c.duration} s — skipped`); warn++; continue; }
  const regs = voiced(wav);
  if (!regs.length) {
    if (DATA.placeholder) skipped.push(c.id);   // js/cues.js from before per-cue flags: a silent take is a placeholder
    else { console.warn(c.id, 'silent take'); warn++; }
    continue;
  }
  const say = strip(c.say || c.text);
  const T = timeline(say, regs);
  const su = textToSay(c.text, say);
  // UTF-16 index (what String.indexOf returns) → seconds
  const at = [];
  [...c.text].forEach((ch, k) => { const s = +T(su[k]).toFixed(3); for (let q = 0; q < ch.length; q++) at.push(s); });
  SYNC[c.id] = { d: c.duration, text: c.text, at };
  n++;
}
const out = `// Generated by sync.mjs from audio/cues/*.wav — re-run it whenever a cue's audio changes. Do not edit.
// SYNC[id].at[i]: seconds after the cue start at which the character text[i] is spoken (measured from the take).
window.SYNC = ${JSON.stringify(SYNC)};
`;
fs.writeFileSync(path.join(ROOT, 'js/sync.js'), out);
console.log(`js/sync.js: ${n} cues measured${warn ? `, ${warn} skipped` : ''}` +
  (skipped.length ? ` · ${skipped.length} placeholder cue(s) not recorded yet, estimate kept: ${skipped.join(', ')} — re-run after recording them` : ''));
