  const canvases = [];
  let t = 0;
  let duration = 0;
  let playing = false;
  let audioStarting = false;
  let anchorT = 0;
  let anchorPerf = 0;
  let scale = 1;
  let rate = 1;             // playback speed (Shift+> / Shift+<)
